// --- Color Space Conversions (sRGB <-> XYZ <-> CIELAB) ---
function srgbToLinear(c) {
  const v = c / 255.0;
  return v > 0.04045 ? Math.pow((v + 0.055) / 1.055, 2.4) : v / 12.92;
}

function rgbToLab(r, g, b) {
  const lr = srgbToLinear(r);
  const lg = srgbToLinear(g);
  const lb = srgbToLinear(b);

  const x = (lr * 0.4124 + lg * 0.3576 + lb * 0.1805) / 0.95047;
  const y = (lr * 0.2126 + lg * 0.7152 + lb * 0.0722) / 1.00000;
  const z = (lr * 0.0193 + lg * 0.1192 + lb * 0.9505) / 1.08883;

  const fx = x > 0.008856 ? Math.cbrt(x) : 7.787 * x + 16 / 116;
  const fy = y > 0.008856 ? Math.cbrt(y) : 7.787 * y + 16 / 116;
  const fz = z > 0.008856 ? Math.cbrt(z) : 7.787 * z + 16 / 116;

  const L = 116 * fy - 16;
  const a = 500 * (fx - fy);
  const bVal = 200 * (fy - fz);
  return [L, a, bVal];
}

function labDistSq(lab1, lab2) {
  const dL = lab1[0] - lab2[0];
  const da = lab1[1] - lab2[1];
  const db = lab1[2] - lab2[2];
  return dL * dL + da * da + db * db;
}

// Find closest Amsterdam acrylic paint
function findClosestAmsterdam(lab) {
  let bestIdx = 0;
  let bestDist = Infinity;
  for (let i = 0; i < AMSTERDAM_PALETTE.length; i++) {
    const d = labDistSq(lab, AMSTERDAM_PALETTE[i].lab);
    if (d < bestDist) {
      bestDist = d;
      bestIdx = i;
    }
  }
  return AMSTERDAM_PALETTE[bestIdx];
}

// --- Preprocessing: Contrast, Brightness, Saturation & Bilateral/Smoothing ---
function preprocessImageData(imageData, config) {
  const { width, height, data } = imageData;
  const gamma = config.gamma ?? 1.0;
  const contrast = config.contrast ?? 1.0;
  const saturation = config.saturation ?? 1.0;
  const smooth = config.smooth ?? true;

  const out = new Uint8ClampedArray(data.length);

  // Gamma LUT
  const lut = new Uint8Array(256);
  for (let i = 0; i < 256; i++) {
    let v = i / 255.0;
    if (gamma !== 1.0) v = Math.pow(v, gamma);
    if (contrast !== 1.0) v = (v - 0.5) * contrast + 0.5;
    lut[i] = Math.max(0, Math.min(255, Math.round(v * 255)));
  }

  for (let i = 0; i < data.length; i += 4) {
    let r = lut[data[i]];
    let g = lut[data[i + 1]];
    let b = lut[data[i + 2]];

    if (saturation !== 1.0) {
      const gray = 0.299 * r + 0.587 * g + 0.114 * b;
      r = Math.max(0, Math.min(255, gray + saturation * (r - gray)));
      g = Math.max(0, Math.min(255, gray + saturation * (g - gray)));
      b = Math.max(0, Math.min(255, gray + saturation * (b - gray)));
    }

    out[i] = r;
    out[i + 1] = g;
    out[i + 2] = b;
    out[i + 3] = 255;
  }

  // High-performance 5x5 multi-pass bilateral filter for texture smoothing (asphalt/grain slayer)
  if (smooth) {
    let currentData = out;
    const passes = 2; // 2 passes completely smooth out asphalt pebbles and wall grain while preserving sharp edges
    const sigmaColorSq = 28 * 28 * 2;

    for (let p = 0; p < passes; p++) {
      const smoothed = new Uint8ClampedArray(currentData.length);

      for (let y = 0; y < height; y++) {
        const rowOffset = y * width;
        for (let x = 0; x < width; x++) {
          const centerIdx = (rowOffset + x) * 4;
          const cr = currentData[centerIdx];
          const cg = currentData[centerIdx + 1];
          const cb = currentData[centerIdx + 2];

          let sumR = 0, sumG = 0, sumB = 0, sumW = 0;

          for (let dy = -2; dy <= 2; dy++) {
            const ny = y + dy;
            if (ny < 0 || ny >= height) continue;
            const nRowOffset = ny * width;

            for (let dx = -2; dx <= 2; dx++) {
              const nx = x + dx;
              if (nx < 0 || nx >= width) continue;

              const nIdx = (nRowOffset + nx) * 4;
              const nr = currentData[nIdx];
              const ng = currentData[nIdx + 1];
              const nb = currentData[nIdx + 2];

              const colorDiffSq = (cr - nr)**2 + (cg - ng)**2 + (cb - nb)**2;
              const spatialDistSq = dx * dx + dy * dy;
              const weight = Math.exp(-spatialDistSq / 8.0) * Math.exp(-colorDiffSq / sigmaColorSq);

              sumR += nr * weight;
              sumG += ng * weight;
              sumB += nb * weight;
              sumW += weight;
            }
          }

          smoothed[centerIdx] = Math.round(sumR / sumW);
          smoothed[centerIdx + 1] = Math.round(sumG / sumW);
          smoothed[centerIdx + 2] = Math.round(sumB / sumW);
          smoothed[centerIdx + 3] = 255;
        }
      }
      currentData = smoothed;
    }
    return currentData;
  }

  return out;
}

// --- CIELAB K-Means Clustering ---
function quantizeCielab(pixels, width, height, k) {
  const numPixels = width * height;
  
  // Step 1: Precompute CIELAB for all pixels
  const labData = new Float32Array(numPixels * 3);
  for (let i = 0; i < numPixels; i++) {
    const pIdx = i * 4;
    const lab = rgbToLab(pixels[pIdx], pixels[pIdx + 1], pixels[pIdx + 2]);
    labData[i * 3] = lab[0];
    labData[i * 3 + 1] = lab[1];
    labData[i * 3 + 2] = lab[2];
  }

  // Step 2: Sample subset for fast centroid convergence (up to 12,000 pixels)
  const sampleStride = Math.max(1, Math.floor(numPixels / 12000));
  const sampleIndices = [];
  for (let i = 0; i < numPixels; i += sampleStride) {
    sampleIndices.push(i);
  }

  // Step 3: K-Means++ initialization on sampled pixels
  const centroids = [];
  // First centroid: random sample
  const firstIdx = sampleIndices[Math.floor(Math.random() * sampleIndices.length)];
  centroids.push([labData[firstIdx * 3], labData[firstIdx * 3 + 1], labData[firstIdx * 3 + 2]]);

  for (let c = 1; c < k; c++) {
    let maxDist = -1;
    let chosenIdx = sampleIndices[0];

    // Pick candidate with probability weighted by distance to nearest centroid
    let sumDists = 0;
    const dists = new Float32Array(sampleIndices.length);
    for (let s = 0; s < sampleIndices.length; s++) {
      const idx = sampleIndices[s];
      const lab = [labData[idx * 3], labData[idx * 3 + 1], labData[idx * 3 + 2]];
      let minDist = Infinity;
      for (let j = 0; j < centroids.length; j++) {
        const d = labDistSq(lab, centroids[j]);
        if (d < minDist) minDist = d;
      }
      dists[s] = minDist;
      sumDists += minDist;
    }

    const target = Math.random() * sumDists;
    let accum = 0;
    for (let s = 0; s < sampleIndices.length; s++) {
      accum += dists[s];
      if (accum >= target) {
        chosenIdx = sampleIndices[s];
        break;
      }
    }

    centroids.push([labData[chosenIdx * 3], labData[chosenIdx * 3 + 1], labData[chosenIdx * 3 + 2]]);
  }

  // Step 4: Iterative K-Means refinement (10 iterations)
  const iterations = 10;
  for (let iter = 0; iter < iterations; iter++) {
    const sums = Array.from({ length: k }, () => [0, 0, 0]);
    const counts = new Uint32Array(k);

    for (let s = 0; s < sampleIndices.length; s++) {
      const idx = sampleIndices[s];
      const lab = [labData[idx * 3], labData[idx * 3 + 1], labData[idx * 3 + 2]];

      let bestC = 0;
      let bestD = Infinity;
      for (let c = 0; c < k; c++) {
        const d = labDistSq(lab, centroids[c]);
        if (d < bestD) {
          bestD = d;
          bestC = c;
        }
      }

      sums[bestC][0] += lab[0];
      sums[bestC][1] += lab[1];
      sums[bestC][2] += lab[2];
      counts[bestC]++;
    }

    for (let c = 0; c < k; c++) {
      if (counts[c] > 0) {
        centroids[c][0] = sums[c][0] / counts[c];
        centroids[c][1] = sums[c][1] / counts[c];
        centroids[c][2] = sums[c][2] / counts[c];
      }
    }
  }

  // Step 5: Assign every pixel to nearest centroid
  const pixelClusters = new Uint8Array(numPixels);
  for (let i = 0; i < numPixels; i++) {
    const lab = [labData[i * 3], labData[i * 3 + 1], labData[i * 3 + 2]];
    let bestC = 0;
    let bestD = Infinity;
    for (let c = 0; c < k; c++) {
      const d = labDistSq(lab, centroids[c]);
      if (d < bestD) {
        bestD = d;
        bestC = c;
      }
    }
    pixelClusters[i] = bestC;
  }

  // Step 6: Map centroids to Amsterdam paints
  const mappedPalette = [];
  const usedCodes = new Set();

  for (let c = 0; c < k; c++) {
    let amsterdam = findClosestAmsterdam(centroids[c]);
    mappedPalette.push({
      clusterId: c,
      name: amsterdam.name,
      code: amsterdam.code,
      rgb: amsterdam.rgb,
      hex: amsterdam.hex,
      lab: amsterdam.lab
    });
  }

  return { pixelClusters, mappedPalette, labData };
}

// --- Connected Component Segmentation & Island Removal ---
function segmentAndCleanIslands(pixelClusters, width, height, palette, minRegionSize) {
  const numPixels = width * height;
  const labels = new Int32Array(numPixels);
  labels.fill(-1);

  let nextRegionId = 0;
  const regionColor = []; // regionId -> palette color index
  const regionPixelCounts = [];

  // Two-pass or Breadth-First-Search flood fill for connected components
  const queue = new Int32Array(numPixels);

  for (let i = 0; i < numPixels; i++) {
    if (labels[i] !== -1) continue;

    const currentCluster = pixelClusters[i];
    const regionId = nextRegionId++;
    regionColor.push(currentCluster);

    let count = 0;
    let qHead = 0;
    let qTail = 0;

    queue[qTail++] = i;
    labels[i] = regionId;

    while (qHead < qTail) {
      const curr = queue[qHead++];
      count++;
      const cx = curr % width;
      const cy = Math.floor(curr / width);

      // Check 4 neighbors
      const neighbors = [
        cx > 0 ? curr - 1 : -1,
        cx < width - 1 ? curr + 1 : -1,
        cy > 0 ? curr - width : -1,
        cy < height - 1 ? curr + width : -1
      ];

      for (let n = 0; n < 4; n++) {
        const nIdx = neighbors[n];
        if (nIdx !== -1 && labels[nIdx] === -1 && pixelClusters[nIdx] === currentCluster) {
          labels[nIdx] = regionId;
          queue[qTail++] = nIdx;
        }
      }
    }

    regionPixelCounts.push(count);
  }

  // Iterative Island Removal:
  // Merge any component with area < minRegionSize into the most color-similar adjacent component
  if (minRegionSize > 1) {
    const parent = new Int32Array(nextRegionId);
    for (let r = 0; r < nextRegionId; r++) parent[r] = r;

    function findRoot(r) {
      let root = r;
      while (root !== parent[root]) root = parent[root];
      let curr = r;
      while (curr !== root) {
        const nxt = parent[curr];
        parent[curr] = root;
        curr = nxt;
      }
      return root;
    }

    // Build region adjacency graph
    const adj = Array.from({ length: nextRegionId }, () => new Set());
    for (let y = 0; y < height; y++) {
      for (let x = 0; x < width; x++) {
        const idx = y * width + x;
        const r1 = labels[idx];
        if (x < width - 1) {
          const r2 = labels[idx + 1];
          if (r1 !== r2) {
            adj[r1].add(r2);
            adj[r2].add(r1);
          }
        }
        if (y < height - 1) {
          const r2 = labels[idx + width];
          if (r1 !== r2) {
            adj[r1].add(r2);
            adj[r2].add(r1);
          }
        }
      }
    }

    // Queue of small regions sorted by size
    const smallRegions = [];
    for (let r = 0; r < nextRegionId; r++) {
      if (regionPixelCounts[r] < minRegionSize) {
        smallRegions.push(r);
      }
    }
    smallRegions.sort((a, b) => regionPixelCounts[a] - regionPixelCounts[b]);

    // Multi-pass iterative merging: ensure NO regions smaller than minRegionSize remain
    let passes = 0;
    while (passes < 5) {
      passes++;
      let anyMerged = false;

      // Find small active roots sorted by size
      const smallRoots = [];
      for (let r = 0; r < nextRegionId; r++) {
        if (parent[r] === r && regionPixelCounts[r] < minRegionSize) {
          smallRoots.push(r);
        }
      }

      if (smallRoots.length === 0) break;
      smallRoots.sort((a, b) => regionPixelCounts[a] - regionPixelCounts[b]);

      for (let i = 0; i < smallRoots.length; i++) {
        const r = findRoot(smallRoots[i]);
        if (regionPixelCounts[r] >= minRegionSize) continue;

        const neighbors = adj[r];
        if (!neighbors || neighbors.size === 0) continue;

        const rLab = palette[regionColor[r]].lab;
        let bestNeighbor = -1;
        let minDeltaE = Infinity;

        for (const n of neighbors) {
          const nRoot = findRoot(n);
          if (nRoot === r) continue;

          const nLab = palette[regionColor[nRoot]].lab;
          const dist = labDistSq(rLab, nLab);
          if (dist < minDeltaE) {
            minDeltaE = dist;
            bestNeighbor = nRoot;
          }
        }

        if (bestNeighbor !== -1) {
          parent[r] = bestNeighbor;
          regionPixelCounts[bestNeighbor] += regionPixelCounts[r];
          anyMerged = true;

          // Merge adjacency sets
          for (const n of neighbors) {
            const nRoot = findRoot(n);
            if (nRoot !== bestNeighbor) {
              adj[bestNeighbor].add(nRoot);
              adj[nRoot].add(bestNeighbor);
            }
            adj[nRoot].delete(r);
          }
        }
      }

      if (!anyMerged) break;
    }

    // Flatten labels and relabel to roots
    for (let i = 0; i < numPixels; i++) {
      labels[i] = findRoot(labels[i]);
    }
  }

  // Compact region IDs and recompute final properties
  const uniqueRoots = Array.from(new Set(labels));
  const rootToNewId = new Map();
  uniqueRoots.forEach((root, idx) => rootToNewId.set(root, idx));

  const finalLabels = new Uint32Array(numPixels);
  for (let i = 0; i < numPixels; i++) {
    finalLabels[i] = rootToNewId.get(labels[i]);
  }

  const numFinalRegions = uniqueRoots.length;
  const finalRegionColors = new Uint8Array(numFinalRegions);
  const finalRegionPixelCounts = new Uint32Array(numFinalRegions);

  for (let i = 0; i < numPixels; i++) {
    const reg = finalLabels[i];
    finalRegionColors[reg] = regionColor[labels[i]];
    finalRegionPixelCounts[reg]++;
  }

  return {
    labels: finalLabels,
    regionColors: finalRegionColors,
    regionPixelCounts: finalRegionPixelCounts,
    numRegions: numFinalRegions
  };
}

// --- Boundary Detection ---
function extractBoundaries(labels, width, height) {
  const numPixels = width * height;
  const boundaries = new Uint8Array(numPixels);

  for (let y = 0; y < height; y++) {
    const rowOffset = y * width;
    for (let x = 0; x < width; x++) {
      const idx = rowOffset + x;
      const curr = labels[idx];

      let isBoundary = false;
      if (x < width - 1 && labels[idx + 1] !== curr) isBoundary = true;
      else if (y < height - 1 && labels[idx + width] !== curr) isBoundary = true;
      else if (x > 0 && labels[idx - 1] !== curr) isBoundary = true;
      else if (y > 0 && labels[idx - width] !== curr) isBoundary = true;

      if (isBoundary) boundaries[idx] = 1;
    }
  }
  return boundaries;
}

// --- Polylabel / Pole of Inaccessibility (Optimal Number Center) ---
function computeRegionCenters(labels, width, height, numRegions) {
  // Find bounding box for each region
  const minX = new Int32Array(numRegions).fill(width);
  const maxX = new Int32Array(numRegions).fill(-1);
  const minY = new Int32Array(numRegions).fill(height);
  const maxY = new Int32Array(numRegions).fill(-1);

  for (let y = 0; y < height; y++) {
    const rowOffset = y * width;
    for (let x = 0; x < width; x++) {
      const reg = labels[rowOffset + x];
      if (x < minX[reg]) minX[reg] = x;
      if (x > maxX[reg]) maxX[reg] = x;
      if (y < minY[reg]) minY[reg] = y;
      if (y > maxY[reg]) maxY[reg] = y;
    }
  }

  const centers = [];

  for (let r = 0; r < numRegions; r++) {
    const bx0 = minX[r], bx1 = maxX[r];
    const by0 = minY[r], by1 = maxY[r];
    const bw = bx1 - bx0 + 1;
    const bh = by1 - by0 + 1;

    // Small or narrow bounding boxes: sample fast
    let bestX = Math.floor((bx0 + bx1) / 2);
    let bestY = Math.floor((by0 + by1) / 2);
    let bestRadius = 0;

    // Grid sampling to find the inscribed circle center (Pole of Inaccessibility)
    const step = Math.max(1, Math.floor(Math.min(bw, bh) / 16));

    for (let py = by0; py <= by1; py += step) {
      for (let px = bx0; px <= bx1; px += step) {
        const pIdx = py * width + px;
        if (labels[pIdx] !== r) continue;

        // Compute distance to nearest non-r boundary pixel
        let minDist = Math.min(px - bx0, bx1 - px, py - by0, by1 - py) + 1;
        const searchDist = Math.min(minDist, 40);

        for (let dy = -searchDist; dy <= searchDist; dy += 2) {
          const sy = py + dy;
          if (sy < 0 || sy >= height) {
            minDist = Math.min(minDist, Math.abs(dy));
            continue;
          }
          for (let dx = -searchDist; dx <= searchDist; dx += 2) {
            const sx = px + dx;
            if (sx < 0 || sx >= width || labels[sy * width + sx] !== r) {
              const d = Math.sqrt(dx * dx + dy * dy);
              if (d < minDist) minDist = d;
            }
          }
        }

        if (minDist > bestRadius) {
          bestRadius = minDist;
          bestX = px;
          bestY = py;
        }
      }
    }

    centers.push({
      x: bestX,
      y: bestY,
      radius: Math.round(bestRadius)
    });
  }

  return centers;
}

// --- Main Worker Message Handler ---
self.onmessage = function (e) {
  const { type, imageData, config } = e.data;

  if (type === 'process') {
    try {
      const { width, height } = imageData;
      const totalPixels = width * height;

      // 1. Preprocess
      self.postMessage({ type: 'progress', step: 1, total: 6, msg: 'Bild vorverarbeiten & glätten...' });
      const processedPixels = preprocessImageData(imageData, config);

      // 2. CIELAB Quantization
      self.postMessage({ type: 'progress', step: 2, total: 6, msg: `Farbquantisierung (${config.colors} Farben in CIELAB)...` });
      const { pixelClusters, mappedPalette } = quantizeCielab(processedPixels, width, height, config.colors);

      // 3. Island Cleaning & Segmentation
      self.postMessage({ type: 'progress', step: 3, total: 6, msg: 'Flächen segmentieren & kleine Inseln bereinigen...' });
      const { labels, regionColors, regionPixelCounts, numRegions } = segmentAndCleanIslands(
        pixelClusters,
        width,
        height,
        mappedPalette,
        config.minRegionSize ?? 80
      );

      // 4. Outlines Extraction
      self.postMessage({ type: 'progress', step: 4, total: 6, msg: 'Konturlinien berechnen...' });
      const boundaries = extractBoundaries(labels, width, height);

      // 5. Smart Number Placement (Pole of Inaccessibility)
      self.postMessage({ type: 'progress', step: 5, total: 6, msg: 'Zahlenpositionen optimal platzieren (Polylabel)...' });
      const centers = computeRegionCenters(labels, width, height, numRegions);

      // 6. Build Final Legend & Compact Palette
      self.postMessage({ type: 'progress', step: 6, total: 6, msg: 'Farblegende und Vorlage zusammenstellen...' });

      // Count usage of each palette color in the final cleaned image
      const paletteUsage = new Uint32Array(mappedPalette.length);
      const paletteRegions = Array.from({ length: mappedPalette.length }, () => 0);

      for (let r = 0; r < numRegions; r++) {
        const cIdx = regionColors[r];
        paletteUsage[cIdx] += regionPixelCounts[r];
        paletteRegions[cIdx]++;
      }

      // Filter out unused palette colors and renumber 1...K
      const activeColors = [];
      const colorRemap = new Map();

      for (let c = 0; c < mappedPalette.length; c++) {
        if (paletteUsage[c] > 0) {
          const number = activeColors.length + 1;
          colorRemap.set(c, number);
          activeColors.push({
            number,
            name: mappedPalette[c].name,
            code: mappedPalette[c].code,
            rgb: mappedPalette[c].rgb,
            hex: mappedPalette[c].hex,
            pixelCount: paletteUsage[c],
            regionCount: paletteRegions[c],
            areaPercent: ((paletteUsage[c] / totalPixels) * 100).toFixed(1)
          });
        }
      }

      // Prepare regions metadata for client rendering
      const regions = [];
      for (let r = 0; r < numRegions; r++) {
        const cIdx = regionColors[r];
        const num = colorRemap.get(cIdx);
        regions.push({
          id: r,
          number: num,
          colorIdx: cIdx,
          x: centers[r].x,
          y: centers[r].y,
          radius: centers[r].radius,
          area: regionPixelCounts[r]
        });
      }

      self.postMessage({
        type: 'complete',
        result: {
          width,
          height,
          labels,
          boundaries,
          palette: activeColors,
          regions
        }
      }, [labels.buffer, boundaries.buffer]);

    } catch (err) {
      self.postMessage({ type: 'error', error: err.message, stack: err.stack });
    }
  }
};
